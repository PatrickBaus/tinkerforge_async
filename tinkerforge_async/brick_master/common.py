@unique
class ConnectionType(Enum):
    """
    The physical connection to the master brick.
    """

    NONE = 0
    USB = 1
    SPI_STACK = 2
    CHIBI = 3
    RS485 = 4
    WIFI = 5
    ETHERNET = 6
    WIFI_V2 = 7


class MasterConnection(Device):
    """
    The connection of the Master Brick to the host.
    """

    async def get_connection_type(self) -> ConnectionType:
        """
        Returns the type of the connection over which this function was called.

        .. versionadded:: 2.4.0$nbsp;(Firmware)
        """
        _, payload = await self.ipcon.send_request(
            device=self, function_id=FunctionID.GET_CONNECTION_TYPE, response_expected=True
        )

        return ConnectionType(unpack_payload(payload, "B"))
